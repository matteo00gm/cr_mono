#!/usr/bin/env node
/**
 * Emits `docs/security/threat-coverage.md` — the T1–T10 matrix as a reviewer,
 * an auditor or a procurement questionnaire reads it (P4-17).
 *
 * Generated from `packages/security/test/threats/threats.json`, the same file
 * the named threat suites and `pnpm test:security` read, so the document cannot
 * claim evidence the suites do not check — and `--check` in CI fails the moment
 * the two disagree.
 *
 * Usage:
 *   node scripts/threat-coverage.mjs           # write the file
 *   node scripts/threat-coverage.mjs --check   # fail if the committed file differs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { die as reportDie } from './lib/report.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const MANIFEST = join(ROOT, 'packages', 'security', 'test', 'threats', 'threats.json');
const OUT = join(ROOT, 'docs', 'security', 'threat-coverage.md');

const die = (msg) => reportDie('threat coverage failed: ' + msg);

const { threats } = JSON.parse(readFileSync(MANIFEST, 'utf8'));

const RUNNER = { unit: 'unit', integration: 'integration (Postgres)', e2e: 'browser (Playwright)' };

/** Escapes the one character that would break a Markdown table cell. */
const cell = (text) => text.replaceAll('|', '\\|');

const section = (threat) => {
  const file = `packages/security/test/threats/${threat.id}-${threat.slug}.test.ts`;
  const evidence = threat.evidence
    .map(
      (item) =>
        `| [\`${item.path}\`](../../${item.path}) | ${RUNNER[item.runner]} | ${cell(item.covers)} |`,
    )
    .join('\n');
  const gaps =
    threat.gaps.length === 0
      ? '_No known gap._'
      : threat.gaps.map((gap) => `- ${gap.what} — **${gap.row}**`).join('\n');

  return [
    `## ${threat.id} — ${threat.goal}`,
    '',
    `**Control.** ${threat.control}`,
    '',
    `**Suite.** [\`${file}\`](../../${file})`,
    '',
    '| Evidence | Runs as | What it proves |',
    '|---|---|---|',
    evidence,
    '',
    `**Gaps.** ${threat.gaps.length === 0 ? gaps : ''}`,
    ...(threat.gaps.length === 0 ? [] : ['', gaps]),
  ].join('\n');
};

const summary = threats
  .map(
    (threat) =>
      `| [${threat.id}](#${threat.id.toLowerCase()}--${threat.goal
        .toLowerCase()
        .replaceAll(/[^a-z0-9 -]/g, '')
        .trim()
        .replaceAll(' ', '-')}) | ${cell(threat.goal)} | ${String(threat.evidence.length)} | ${
        threat.gaps.length === 0 ? '—' : threat.gaps.map((gap) => gap.row).join(', ')
      } |`,
  )
  .join('\n');

const body =
  `<!-- Generated by scripts/threat-coverage.mjs from packages/security/test/threats/threats.json. Do not edit. -->\n\n` +
  `# Threat coverage\n\n` +
  `The T1–T10 threat model from the plan's §3.0, and for each threat the control\n` +
  `and the tests that are its evidence. Every file listed here is checked to exist\n` +
  `and to hold a test by its threat's suite, and \`pnpm test:security\` runs exactly\n` +
  `these files. A gap is work a later row owns; it is named, never hidden, and it\n` +
  `shows as a \`todo\` in every run.\n\n` +
  `| Threat | Attacker goal | Evidence | Open gaps |\n|---|---|---|---|\n` +
  `${summary}\n\n` +
  threats.map(section).join('\n\n') +
  '\n';

if (process.argv.includes('--check')) {
  if (!existsSync(OUT)) die(`${OUT} does not exist. Run \`pnpm threats\` and commit it.`);
  if (readFileSync(OUT, 'utf8') !== body) {
    die('the committed threat coverage is stale. Run `pnpm threats` and commit the result.');
  }
  console.log('\n  Threat coverage is current.\n');
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, body, 'utf8');
  console.log(`\n  Wrote ${OUT} (${String(threats.length)} threats)\n`);
}
