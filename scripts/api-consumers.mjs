#!/usr/bin/env node
/**
 * Emits `docs/api/consumers.md` — an endpoint → call-site table (P0-63).
 *
 * This answers the half of "document the endpoints" that prose cannot: **where
 * and how each one is used.** A hand-maintained consumer list is wrong the first
 * time somebody adds a call site; this one is derived from the calls themselves,
 * so it cannot be.
 *
 * It works only because every call goes through `@catalogorosso/api-client` and
 * names its endpoint as a literal key. The ESLint rule forbidding raw `fetch` to
 * our own API is what keeps that true — without it this map would quietly become
 * a subset and nobody would know which subset.
 *
 * Usage:
 *   node scripts/api-consumers.mjs           # write the file
 *   node scripts/api-consumers.mjs --check   # fail if the committed file differs
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import process from 'node:process';
import { die as reportDie } from './lib/report.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'docs', 'api', 'consumers.md');

const die = (msg) => reportDie('consumer map failed: ' + msg);

/** Where a consumer could live. The client's own package is not a consumer. */
const ROOTS = ['apps', 'packages'].map((group) => join(ROOT, group));
const SKIP = new Set(['node_modules', 'dist', 'coverage', '.turbo', 'test']);

const sources = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(entry.name)) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (/\.(ts|tsx)$/.test(entry.name)) sources.push(path);
  }
};
for (const root of ROOTS) if (existsSync(root) && statSync(root).isDirectory()) walk(root);

/** `request('GET /v1/dashboard/me')` — the endpoint is always a literal. */
const CALL = /\.request\(\s*'((?:GET|POST|PUT|PATCH|DELETE) \/v1\/[^']*)'/g;

const byEndpoint = new Map();

for (const path of sources) {
  const rel = relative(ROOT, path).split(sep).join('/');
  if (rel.startsWith('packages/api-client/')) continue;

  const body = readFileSync(path, 'utf8');
  for (const match of body.matchAll(CALL)) {
    const endpoint = match[1];
    const line = body.slice(0, match.index).split('\n').length;
    if (!byEndpoint.has(endpoint)) byEndpoint.set(endpoint, []);
    byEndpoint.get(endpoint).push(`${rel}:${String(line)}`);
  }
}

const endpoints = [...byEndpoint.keys()].sort();

const body =
  `<!-- Generated by scripts/api-consumers.mjs. Do not edit. -->\n\n` +
  `# API consumers\n\n` +
  `Which endpoints are called, and from where. Derived from the calls\n` +
  `themselves rather than maintained by hand, so it cannot fall behind — and\n` +
  `complete only because raw \`fetch\` to our own API is forbidden outside\n` +
  `\`@catalogorosso/api-client\` (P0-63).\n\n` +
  (endpoints.length === 0
    ? '_No call sites yet. The dashboard (P0-57) and widget (P3) are the first consumers._\n'
    : `| Endpoint | Called from |\n|---|---|\n` +
      endpoints
        .map((endpoint) => `| \`${endpoint}\` | ${byEndpoint.get(endpoint).sort().join('<br>')} |`)
        .join('\n') +
      '\n');

if (process.argv.includes('--check')) {
  if (!existsSync(OUT)) die(`${OUT} does not exist. Run \`pnpm consumers\` and commit it.`);
  if (readFileSync(OUT, 'utf8') !== body) {
    die('the committed consumer map is stale. Run `pnpm consumers` and commit the result.');
  }
  console.log('\n  Consumer map is current.\n');
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, body, 'utf8');
  console.log(`\n  Wrote ${OUT} (${String(endpoints.length)} endpoints called)\n`);
}
